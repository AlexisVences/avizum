"""Builds src/assets/cdmxMap.js, the faint CDMX map behind the chat, from the official alcaldías boundaries.

Source: "Límite de Alcaldías (áreas geoestadísticas municipales)", datos abiertos de la Ciudad de México
(https://datos.cdmx.gob.mx/dataset/alcaldias). The GeoJSON is downloaded, projected, simplified and written as paths;
the 770 KB original is not committed.

Usage (from frontend/): python3 scripts/build_cdmx_map.py [path-to-alcaldias.geojson]
"""
import json
import math
import sys
import urllib.request
from pathlib import Path

URL = ("https://datos.cdmx.gob.mx/dataset/bae265a8-d1f6-4614-b399-4184bc93e027/resource/"
       "deb5c583-84e2-4e07-a706-1b3a0dbc99b0/download/deb5c583-84e2-4e07-a706-1b3a0dbc99b0.json")
OUT = Path(__file__).resolve().parents[1] / "src" / "assets" / "cdmxMap.js"
SCALE = 2000          # units per degree of latitude
TOLERANCE = 0.00035   # degrees (~40 m): invisible at the size the map is drawn
# Names printed around the map, with the side they sit on, as in the approved mockup. The side is chosen by hand because
# two alcaldías that are both west of the center would otherwise print their names on top of each other.
LABELS = {
    "Gustavo A. Madero": ("GUSTAVO A. MADERO", "right"), "Miguel Hidalgo": ("MIGUEL HIDALGO", "left"),
    "Iztacalco": ("IZTACALCO", "right"), "Álvaro Obregón": ("ÁLVARO OBREGÓN", "left"),
    "Iztapalapa": ("IZTAPALAPA", "right"), "Coyoacán": ("COYOACÁN", "right"), "Tlalpan": ("TLALPAN", "left"),
}


def simplify(points, tolerance):
    """Douglas-Peucker on a ring of (x, y). A closed ring starts and ends on the same point, which has no line to measure
    against, so it is cut at its farthest point and each half is simplified on its own."""
    if len(points) < 4:
        return points
    if points[0] == points[-1]:
        far = max(range(1, len(points) - 1), key=lambda i: math.hypot(points[i][0] - points[0][0], points[i][1] - points[0][1]))
        return simplify(points[: far + 1], tolerance)[:-1] + simplify(points[far:], tolerance)
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = points[a], points[b]
        dx, dy = bx - ax, by - ay
        norm = math.hypot(dx, dy) or 1e-12
        far, index = 0.0, None
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / norm
            if d > far:
                far, index = d, i
        if index is not None and far > tolerance:
            keep[index] = True
            stack += [(a, index), (index, b)]
    return [p for p, k in zip(points, keep) if k]


def main() -> None:
    raw = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(URL, timeout=60).read()
    features = json.loads(raw)["features"]
    rings = [(f["properties"]["NOMGEO"], [r for poly in (f["geometry"]["coordinates"] if f["geometry"]["type"] == "MultiPolygon" else [f["geometry"]["coordinates"]]) for r in poly]) for f in features]
    lons = [x for _, rs in rings for r in rs for x, _ in r]
    lats = [y for _, rs in rings for r in rs for _, y in r]
    lon0, lat0 = (min(lons) + max(lons)) / 2, (min(lats) + max(lats)) / 2
    k = math.cos(math.radians(lat0))
    project = lambda lon, lat: ((lon - lon0) * k * SCALE, -(lat - lat0) * SCALE)

    alcaldias, xs, ys = [], [], []
    for name, rs in sorted(rings):
        d = []
        for ring in rs:
            pts = simplify([(x, y) for x, y in ring], TOLERANCE)
            proj = [project(x, y) for x, y in pts]
            xs += [p[0] for p in proj]
            ys += [p[1] for p in proj]
            d.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in proj) + "Z")
        cx = sum(x for r in rs for x, _ in r) / sum(len(r) for r in rs)
        cy = sum(y for r in rs for _, y in r) / sum(len(r) for r in rs)
        alcaldias.append({"name": name, "d": "".join(d), "centroid": [round(v, 1) for v in project(cx, cy)]})

    box = {"minX": round(min(xs), 1), "maxX": round(max(xs), 1), "minY": round(min(ys), 1), "maxY": round(max(ys), 1)}
    labels = [{"text": LABELS[a["name"]][0], "side": LABELS[a["name"]][1], "y": a["centroid"][1]} for a in alcaldias if a["name"] in LABELS]
    body = json.dumps({"box": box, "alcaldias": [{"name": a["name"], "d": a["d"]} for a in alcaldias], "labels": labels}, ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/build_cdmx_map.py. Do not edit by hand.\n"
        "// Source: Límite de Alcaldías, datos abiertos de la Ciudad de México (datos.cdmx.gob.mx/dataset/alcaldias).\n"
        f"const cdmxMap = {body};\n\nexport default cdmxMap;\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(OUT.parents[2])}: {OUT.stat().st_size // 1024} KB, {len(alcaldias)} alcaldías, box {box}")


if __name__ == "__main__":
    main()
